BEGIN = '\t# BEGIN generated contact buttons'
END = '\t# END generated contact buttons'


def gen_je_block():
    path = os.path.join(ROOT, 'common/journal_entries/nesnd_unification.txt')
    with open(path, 'rb') as f:
        raw = f.read().decode('utf-8-sig')
    text = raw.replace('\r\n', '\n')
    lines = text.split('\n')
    try:
        b = lines.index(BEGIN)
        e = lines.index(END)
    except ValueError:
        raise SystemExit('markers not found in ' + path)
    new = lines[:b + 1] + ['\tscripted_button = nesnd_uni_contact_%s' % s for s in ALL] + lines[e:]
    write('common/journal_entries/nesnd_unification.txt', '\n'.join(new))


