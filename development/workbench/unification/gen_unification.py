def write(rel, text, crlf=True):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = text.replace('\r\n', '\n')
    if crlf:
        text = text.replace('\n', '\r\n')
    with open(path, 'wb') as f:
        f.write((BOM + text).encode('utf-8'))
    return path


def gen_triggers():
    out = []
    out.append('# Generated by development/workbench/unification/gen_unification.py. Do not edit by hand.')
    out.append('')
    out.append('# state_region scope: the region belongs to the 95 regions of the unification scope.')
    out.append('nesnd_uni_scope_region = {')
    out.append('\tOR = {')
    for s in ALL:
        out.append('\t\tthis = s:%s' % s)
    out.append('\t}')
    out.append('}')
    out.append('')
    write('common/scripted_triggers/nesnd_unification_generated.txt', '\n'.join(out))


def value_block(name, comment, per_region):
    out = ['# ' + comment, name + ' = {', '\tvalue = 0']
    for s in ALL:
        out.extend(per_region(s))
    out.append('}')
    out.append('')
    return out


def gen_values():
    out = ['# Generated by development/workbench/unification/gen_unification.py. Do not edit by hand.', '']

    def own(s):
        return ['\tif = {',
                '\t\tlimit = { owns_entire_state_region = %s }' % s,
                '\t\tadd = 1',
                '\t}']

    def fading(s):
        lines = ['\tif = {',
                 '\t\tlimit = {',
                 '\t\t\thas_claim = s:%s' % s,
                 '\t\t\tNOT = { country_or_subject_owns_entire_state_region = %s }' % s]
        if s in QE1_KEEP:
            lines.append('\t\t\tNOT = { c:QE1 ?= this }')
        lines += ['\t\t}', '\t\tadd = 1', '\t}']
        return lines

    out += value_block('nesnd_uni_own_count',
                       'Country scope: regions of the 95 owned whole by the country itself.', own)
    out += value_block('nesnd_uni_fading_claim_count',
                       'Country scope: claimed regions of the 95 not yet held whole (QE1 keeps Gansu and Hexi claims).', fading)
    write('common/script_values/nesnd_unification_generated.txt', '\n'.join(out))


